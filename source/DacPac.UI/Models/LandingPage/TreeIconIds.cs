namespace DacPac.UI.Models.LandingPage;

/// <summary>
/// Defines the icon identifiers used by items in the landing page tree.
/// </summary>
public static class TreeIconIds
{
    /// <summary>
    /// Identifies the icon used for a folder of related database objects.
    /// </summary>
    public const string Folder = nameof(Folder);

    /// <summary>
    /// Identifies the icon used for a database schema.
    /// </summary>
    public const string Schema = nameof(Schema);

    /// <summary>
    /// Identifies the icon used for a database table.
    /// </summary>
    public const string Table = nameof(Table);

    /// <summary>
    /// Identifies the icon used for a table or view column.
    /// </summary>
    public const string Column = nameof(Column);

    /// <summary>
    /// Identifies the icon used for a stored procedure parameter.
    /// </summary>
    public const string Parameter = nameof(Parameter);

    /// <summary>
    /// Identifies the icon used for a database view.
    /// </summary>
    public const string View = nameof(View);

    /// <summary>
    /// Identifies the icon used for a stored procedure.
    /// </summary>
    public const string Procedure = nameof(Procedure);
}
